// Builds the Decap CMS "writing" preview template: a browser bundle that
// reuses components/MarkdownBody.tsx (the same rendering pipeline as the
// live site) plus a copy of the real design tokens + article-body CSS,
// so the /admin preview can never silently drift from the published page.
// Runs automatically before `next dev` and `next build` (see package.json).

import { build } from "esbuild";
import { fileURLToPath } from "url";
import path from "path";
import fs from "fs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

await build({
  entryPoints: [path.join(root, "scripts/admin-preview-entry.tsx")],
  bundle: true,
  outfile: path.join(root, "public/admin/markdown-preview.bundle.js"),
  format: "iife",
  target: "es2019",
  jsx: "automatic",
  loader: {
    ".css": "css",
    ".woff": "dataurl",
    ".woff2": "dataurl",
    ".ttf": "dataurl",
  },
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "info",
});

// Share the real design tokens + .article-body ruleset with the admin
// preview, instead of hand-duplicating them — single source of truth.
const globalsCss = fs.readFileSync(path.join(root, "app/globals.css"), "utf8");
const marker = "/* Article body — markdown, code blocks, math */";
const markerIndex = globalsCss.indexOf(marker);
if (markerIndex === -1) {
  throw new Error(`build-admin-preview: could not find "${marker}" in app/globals.css`);
}
const articleBodyCss = globalsCss.slice(markerIndex);

// The preview iframe's background is always light — force the light-theme
// token values as the base (rather than dark, tokens.css's default) so
// headings/text don't render near-white-on-white.
const tokensCss = fs
  .readFileSync(path.join(root, "styles/tokens.css"), "utf8")
  .replace('[data-theme="light"]', ":root");

fs.writeFileSync(
  path.join(root, "public/admin/site.css"),
  `/* Auto-generated by scripts/build-admin-preview.mjs — do not edit directly.\n   Source: styles/tokens.css (light theme forced) + the article-body rules in app/globals.css. */\n\n${tokensCss}\n${articleBodyCss}`
);

console.log("admin preview: wrote public/admin/site.css");
